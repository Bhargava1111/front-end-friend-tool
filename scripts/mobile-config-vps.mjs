#!/usr/bin/env node
/**
 * VPS mobile config — APK loads UI from your VPS (no Lovable).
 * Requires the web frontend to be deployed on the VPS (see install.sh).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

const vpsIp = process.env.VPS_IP?.trim() || "200.234.39.88";
const vpsScheme = process.env.VPS_SCHEME?.trim() || "http";
const vpsBase = `${vpsScheme}://${vpsIp}`;
const vpsApiUrl = process.env.VPS_API_URL?.trim() || `${vpsBase}/api/v1`;

const bundled = process.env.MOBILE_BUNDLED === "1" || process.argv.includes("--bundled");

const mobileDir = path.join(root, "mobile");
fs.mkdirSync(mobileDir, { recursive: true });

const serverConfig = {
  mode: bundled ? "vps-bundled" : "vps-remote",
  bundled,
  // Remote: Capacitor WebView loads the store from your VPS (SSR Node app).
  // Bundled: UI is packaged inside the APK; API still hits VPS.
  serverUrl: bundled ? "" : vpsBase,
  webUrl: vpsBase,
  apiUrl: vpsApiUrl,
  vpsIp,
  updatedAt: new Date().toISOString(),
};

fs.writeFileSync(path.join(mobileDir, "capacitor.server.json"), JSON.stringify(serverConfig, null, 2));

const envLines = [
  `# Auto-generated by scripts/mobile-config-vps.mjs`,
  `VITE_API_URL=${vpsApiUrl}`,
  `API_URL=${vpsApiUrl}`,
  `VITE_VPS_API_URL=${vpsApiUrl}`,
  `VITE_PUBLIC_WEB_URL=${vpsBase}`,
  `VITE_APP_URL=${vpsBase}`,
  bundled ? `# CAPACITOR_SERVER_URL not set — UI bundled in APK` : `CAPACITOR_SERVER_URL=${vpsBase}`,
  ``,
];
fs.writeFileSync(path.join(root, ".env.mobile.local"), envLines.join("\n"));

console.log("");
console.log("VPS mobile config ready (no Lovable)");
console.log("====================================");
console.log(`Web app URL:   ${vpsBase}`);
console.log(`VPS API:       ${vpsApiUrl}`);
console.log(`APK mode:      ${bundled ? "bundled UI in APK" : "loads UI from VPS"}`);
if (!bundled) {
  console.log("");
  console.log("Deploy frontend on VPS first:");
  console.log("  bash /var/www/mnxstore/backend/deploy/vps/install.sh");
}
console.log("");
console.log("Next: npm run mobile:apk:vps");
console.log("");
